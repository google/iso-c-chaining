"""Generates a single-header stb-style distribution (`chain_single.h`).

Usage:
  python3 tools/make_single_header.py --output chain_single.h

In one C/C++ translation unit, define `CHAIN_IMPLEMENTATION` before including
the generated header to compile the runtime implementation:

  #define CHAIN_IMPLEMENTATION
  #include "chain_single.h"

To include the SQLite3 `Db` extension (`ext/db.h` and `ext/db.c`), define
`CHAIN_ENABLE_DB` (or `#include <sqlite3.h>`) before including `chain_single.h`
and link with `-lsqlite3`.
"""

import argparse
import pathlib
import re
import sys

CORE_SOURCES = [
    ("boolean", "core/boolean.c"),
    ("null", "core/null.c"),
    ("number", "core/number.c"),
    ("string", "core/string.c"),
    ("slice", "core/slice.c"),
    ("hash", "core/hash.c"),
    ("status_or", "core/status_or.c"),
    ("json", "core/json.c"),
]

EXT_SOURCES = [
    ("server", "ext/server.c"),
    ("test", "ext/test.c"),
]

DB_SOURCE = ("db", "ext/db.c")

LOCAL_INCLUDE_RE = re.compile(r'^\s*#\s*include\s+"([^"]+)"\s*$')
SYS_INCLUDE_RE = re.compile(r"^\s*#\s*include\s+<([^>]+)>\s*$")
HEADER_GUARD_RE = re.compile(
    r"^\s*#\s*(ifndef|endif)\b.*CHAIN_[A-Z0-9_]*_H_"
)

STATIC_DECL_RE = re.compile(
    r"^static\s+(?:[A-Za-z_][A-Za-z0-9_]*(?:\s+|\s*\*+\s*))+"
    r"([A-Za-z_][A-Za-z0-9_]*)\s*(?:\(|=)",
    re.MULTILINE,
)
TYPEDEF_STRUCT_RE = re.compile(
    r"^}\s*([A-Za-z_][A-Za-z0-9_]*)\s*;",
    re.MULTILINE,
)

# Tokenizer matching C comments, string/char literals, or (`->`/`.` +) symbols.
C_TOKEN_RE = re.compile(
    r"//[^\n]*|"
    r"/\*[\s\S]*?\*/|"
    r'"(?:\\.|[^"\\])*"|'
    r"'(?:\\.|[^'\\])*'|"
    r"(?:->|\.)\s*[A-Za-z_][A-Za-z0-9_]*|"
    r"\b[A-Za-z_][A-Za-z0-9_]*\b"
)

BANNER_PREFIX = (
    "/*\n"
    " * Copyright 2026 Google LLC\n"
    " *\n"
    ' * Licensed under the Apache License, Version 2.0 (the "License");\n'
    " * you may not use this file except in compliance with the License.\n"
    " * You may obtain a copy of the License at\n"
    " *\n"
    " *     https://www.apache.org/licenses/LICENSE-2.0\n"
    " *\n"
    " * Unless required by applicable law or agreed to in writing, software\n"
    ' * distributed under the License is distributed on an "AS IS" BASIS,\n'
    " * WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or"
    " implied.\n"
    " * See the License for the specific language governing permissions and\n"
    " * limitations under the License.\n"
    " *\n"
    " * chain_single.h - Single-header distribution of C Chaining.\n"
    " *\n"
    " * Auto-generated by tools/make_single_header.py. Do not edit.\n"
    " *\n"
    " * Usage:\n"
    " *   In ONE C/C++ source file, define `CHAIN_IMPLEMENTATION`\n"
    " *   before including this header:\n"
    " *\n"
    " *     #define CHAIN_IMPLEMENTATION\n"
    ' *     #include "chain_single.h"\n'
    " *\n"
    " *   Optional configuration macros (define before including):\n"
    " *     #define CHAIN_ENABLE_DB       // Include SQLite3 Db\n"
    " *     #define CHAIN_NO_SHORT_NAMES  // Ch* / ch_* names only\n"
    " */\n"
    "#ifndef CHAIN_SINGLE_H_\n"
    "#define CHAIN_SINGLE_H_\n"
    "#define CHAIN_H_\n"
)

LICENSE_HEADER_RE = re.compile(
    r"^\s*/\*[\s\S]*?Licensed under the Apache License[\s\S]*?\*/\s*",
)

IMPL_PROLOGUE = (
    "#ifdef CHAIN_IMPLEMENTATION\n"
    "#ifndef CHAIN_IMPLEMENTATION_INCLUDED_\n"
    "#define CHAIN_IMPLEMENTATION_INCLUDED_\n\n"
    "#include <arpa/inet.h>\n"
    "#include <ctype.h>\n"
    "#include <math.h>\n"
    "#include <netinet/in.h>\n"
    "#include <poll.h>\n"
    "#include <signal.h>\n"
    "#include <stdbool.h>\n"
    "#include <stddef.h>\n"
    "#include <stdio.h>\n"
    "#include <stdlib.h>\n"
    "#include <string.h>\n"
    "#include <strings.h>\n"
    "#include <sys/socket.h>\n"
    "#include <sys/time.h>\n"
    "#include <unistd.h>\n"
)

IMPL_EPILOGUE = (
    "#endif  /* CHAIN_IMPLEMENTATION_INCLUDED_ */\n"
    "#endif  /* CHAIN_IMPLEMENTATION */\n"
)


def expand_header(rel_path: str, root: pathlib.Path, seen: set[str]) -> str:
  """Recursively expands a project header in-place, stripping local guards."""
  if rel_path in seen:
    return ""
  seen.add(rel_path)

  full_path = root / rel_path
  raw_text = LICENSE_HEADER_RE.sub("", full_path.read_text(encoding="utf-8"))
  lines = raw_text.splitlines()
  out = [f"/* --- begin {rel_path} --- */"]

  for line in lines:
    if HEADER_GUARD_RE.match(line):
      continue
    m_local = LOCAL_INCLUDE_RE.match(line)
    if m_local:
      inc_path = m_local.group(1)
      expanded = expand_header(inc_path, root, seen)
      if expanded:
        out.append(expanded)
      continue
    out.append(line)

  out.append(f"/* --- end {rel_path} --- */")
  return "\n".join(out)


def transform_source(mod_name: str, rel_path: str, root: pathlib.Path) -> str:
  """Transforms a `.c` file so its file-scope static symbols never collide."""
  src = LICENSE_HEADER_RE.sub("", (root / rel_path).read_text(encoding="utf-8"))

  # Strip `#include "..."` and `#include <...>` lines (emitted at section top).
  filtered_lines = []
  for line in src.splitlines():
    if LOCAL_INCLUDE_RE.match(line) or SYS_INCLUDE_RE.match(line):
      continue
    filtered_lines.append(line)
  body = "\n".join(filtered_lines).strip()

  static_syms = set(STATIC_DECL_RE.findall(body))
  static_syms.update(TYPEDEF_STRUCT_RE.findall(body))
  has_self = "self" in static_syms
  static_syms.discard("self")

  def replace_token(match: re.Match[str]) -> str:
    tok = match.group(0)
    if tok in static_syms:
      return f"ch_{mod_name}_{tok}"
    return tok

  transformed = C_TOKEN_RE.sub(replace_token, body)

  out = [f"/* --- begin {rel_path} --- */"]
  if has_self:
    out.append(f"#define self ch_{mod_name}_self")
  out.append(transformed)
  if has_self:
    out.append("#undef self")
  out.append(f"/* --- end {rel_path} --- */")
  return "\n".join(out)


def generate_single_header(root: pathlib.Path) -> str:
  """Builds the complete single-header contents from `root`."""
  seen_headers: set[str] = set()

  core_and_ext_headers = [
      "core/types.h",
      "core/boolean.h",
      "core/null.h",
      "core/number.h",
      "core/string.h",
      "core/slice.h",
      "core/hash.h",
      "core/status_or.h",
      "core/json.h",
      "ext/server.h",
      "ext/test.h",
  ]

  header_chunks = []
  for h in core_and_ext_headers:
    chunk = expand_header(h, root, seen_headers)
    if chunk:
      header_chunks.append(chunk)

  db_header_chunk = expand_header("ext/db.h", root, seen_headers)
  db_header_section = "\n".join([
      "#if !defined(CHAIN_NO_DB) && \\",
      "    (defined(CHAIN_ENABLE_DB) || defined(SQLITE3_H) || \\",
      "     defined(_SQLITE3_H_))",
      "#ifndef CHAIN_HAS_DB_",
      "#define CHAIN_HAS_DB_ 1",
      "#endif",
      db_header_chunk,
      "#endif  /* CHAIN_ENABLE_DB */\n",
  ])

  impl_chunks = [
      transform_source(mod, path, root) for mod, path in CORE_SOURCES
  ]
  for mod, path in EXT_SOURCES:
    impl_chunks.append(transform_source(mod, path, root))

  db_impl_chunk = transform_source(DB_SOURCE[0], DB_SOURCE[1], root)
  db_impl_section = "\n".join([
      "#ifdef CHAIN_HAS_DB_",
      "#include <sqlite3.h>",
      db_impl_chunk,
      "#endif  /* CHAIN_HAS_DB_ */\n",
  ])

  parts = [
      BANNER_PREFIX,
      "\n\n".join(header_chunks),
      db_header_section,
      "#endif  /* CHAIN_SINGLE_H_ */\n",
      IMPL_PROLOGUE,
      "\n\n".join(impl_chunks),
      db_impl_section,
      IMPL_EPILOGUE,
  ]
  return "\n".join(parts)


def main() -> int:
  parser = argparse.ArgumentParser(
      description="Generate single-header chain_single.h amalgamation."
  )
  default_root = pathlib.Path(__file__).resolve().parent.parent
  parser.add_argument(
      "--root",
      type=pathlib.Path,
      default=default_root,
      help="Root directory of the chaining repository.",
  )
  parser.add_argument(
      "--output",
      type=pathlib.Path,
      default=pathlib.Path("chain_single.h"),
      help="Output file path for the generated single header.",
  )
  args = parser.parse_args()

  content = generate_single_header(args.root.resolve())
  args.output.parent.mkdir(parents=True, exist_ok=True)
  args.output.write_text(content, encoding="utf-8")
  return 0


if __name__ == "__main__":
  sys.exit(main())
